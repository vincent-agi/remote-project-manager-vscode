import { COMMIT_SUBJECT_PATTERN_SOURCE } from "./commit-message";

/** First lines of every hook this extension writes; used to recognise it later. */
export const HOOK_MARKER = "# managed by remote-project-manager";

/** What currently occupies the `commit-msg` hook path. */
export type ExistingHookKind = "none" | "managed" | "foreign";

/** Classifies the content of an existing `commit-msg` hook (`undefined` = no file). */
export function classifyExistingHook(content: string | undefined): ExistingHookKind {
  if (content === undefined) {
    return "none";
  }
  return content.includes(HOOK_MARKER) ? "managed" : "foreign";
}

/**
 * The checker run by the hook, as plain JavaScript (no quotes other than
 * double quotes, so it can sit inside a single-quoted shell argument).
 * Merge, revert, fixup and squash commits are let through: they are
 * generated by git and never follow the convention.
 */
function buildCheckerSource(): string {
  const pattern = JSON.stringify(COMMIT_SUBJECT_PATTERN_SOURCE);
  return [
    `const fs = require("fs");`,
    `const text = fs.readFileSync(process.argv[1], "utf8");`,
    `const subject = text.split("\\n").find((line) => line.trim() !== "" && !line.startsWith("#"));`,
    `if (subject === undefined) process.exit(0);`,
    `if (/^(Merge |Revert |fixup! |squash! )/.test(subject)) process.exit(0);`,
    `if (new RegExp(${pattern}, "u").test(subject.trim())) process.exit(0);`,
    `console.error("commit-msg: subject does not match <type>(<scope>): <gitmoji> <description>");`,
    `console.error("  got: " + subject);`,
    `console.error("  e.g. feat(ui): ✨ add a status bar item");`,
    `process.exit(1);`,
  ].join("\n");
}

/**
 * Builds the `commit-msg` hook: a POSIX shell wrapper that runs the
 * checker with `node`, and lets the commit through when `node` is not on
 * the `PATH` (a missing tool must never block committing).
 */
export function buildCommitMsgHookScript(): string {
  const checker = buildCheckerSource().replace(/'/g, `'\\''`);
  return [
    "#!/bin/sh",
    HOOK_MARKER,
    "# Remove it with 'Remote Project Manager: Uninstall Commit Message Hook'.",
    "command -v node >/dev/null 2>&1 || exit 0",
    `exec node -e '${checker}' "$1"`,
    "",
  ].join("\n");
}
